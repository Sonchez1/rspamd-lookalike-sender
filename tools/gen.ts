function nfkc(s: string): string { return s.normalize("NFKC"); }

/** A Lua string literal using decimal \ddd byte escapes (safe on Lua 5.1 / LuaJIT). */
function luaBytes(s: string): string {
  const bytes = Buffer.from(s, "utf8");
  let out = '"';
  for (const b of bytes) out += "\\" + b;
  return out + '"';
}

// --- code point set to probe ------------------------------------------------
const confusables = JSON.parse(readFileSync(resolve(enginePkg, "data/confusables.json"), "utf8")) as Record<string, string>;
const probe = new Set<number>();
for (let cp = 0; cp <= 0x2ffff; cp++) { if (cp >= 0xd800 && cp <= 0xdfff) continue; probe.add(cp); }
for (let cp = 0xe0000; cp <= 0xe0200; cp++) probe.add(cp);
for (const k of Object.keys(confusables)) { const cp = k.codePointAt(0); if (cp !== undefined) probe.add(cp); }
const cps = [...probe].sort((a, b) => a - b);

// --- per-code-point maps (emit only entries that change the character) ------
function emitCpMap(name: string, fn: (ch: string) => string): number {
  const lines: string[] = [`-- Auto-generated by tools/gen.ts. Do not edit by hand.`, `return {`];
  let n = 0;
  for (const cp of cps) {
    const ch = String.fromCodePoint(cp);
    const out = fn(ch);
    if (out === ch) continue;
    lines.push(`  [${cp}]=${luaBytes(out)},`);
    n++;
  }
  lines.push(`}`);
  writeFileSync(resolve(dataDir, `${name}.lua`), lines.join("\n") + "\n");
  return n;
}

const nFold = emitCpMap("cpfold", (c) => foldSkeleton(c));
const nCase = emitCpMap("cpcase", (c) => casefold(c));
const nNorm = emitCpMap("cpnorm", (c) => casefold(nfkc(c)));

// --- ranges for scripts and character classes -------------------------------
function emitRanges(name: string, luaName: string, classify: (cp: number) => string | null, comment: string): number {
  const ranges: [number, number, string][] = [];
  for (const cp of cps) {
    const c = classify(cp);
    if (c === null) continue;
    const last = ranges[ranges.length - 1];
    if (last && last[2] === c && last[1] === cp - 1) last[1] = cp;
    else ranges.push([cp, cp, c]);
  }
  const lines = [`-- ${comment}`, `-- Auto-generated by tools/gen.ts. Do not edit by hand.`, `return {`];
  for (const [lo, hi, c] of ranges) lines.push(`  {${lo},${hi},${JSON.stringify(c)}},`);
  lines.push(`}`);
  writeFileSync(resolve(dataDir, `${luaName}.lua`), lines.join("\n") + "\n");
  return ranges.length;
}

// Reuse the engine's own script ranges verbatim (same source scripts.json it ships).
const scriptRanges = JSON.parse(readFileSync(resolve(enginePkg, "data/scripts.json"), "utf8")) as [number, number, string][];
{
  const lines = [`-- UTS #39 script ranges (copied from impersonation-detector scripts.json).`, `-- Auto-generated by tools/gen.ts. Do not edit by hand.`, `return {`];
  for (const [lo, hi, s] of scriptRanges) lines.push(`  {${lo},${hi},${JSON.stringify(s)}},`);
  lines.push(`}`);
  writeFileSync(resolve(dataDir, `scripts.lua`), lines.join("\n") + "\n");
}

const reLetterNumber = /\p{L}|\p{N}/u;
const reNd = /\p{Nd}/u;
const nWord = emitRanges("wordchars", "wordchars", (cp) => (reLetterNumber.test(String.fromCodePoint(cp)) ? "w" : null), "\\p{L}\\p{N} (word characters for tokenisation)");
const nDigit = emitRanges("digits", "digits", (cp) => (reNd.test(String.fromCodePoint(cp)) ? "d" : null), "\\p{Nd} (decimal digits)");

// --- weights ----------------------------------------------------------------
{
  const w = defaultWeights();
  const lines = [`-- Logistic sender-score weights (copied from scorer_weights.json).`, `-- Auto-generated by tools/gen.ts. Do not edit by hand.`, `return {`, `  feature_names = {`];
  for (const f of FEATURE_NAMES) lines.push(`    ${JSON.stringify(f)},`);
  lines.push(`  },`, `  weights = {`);
  for (const f of FEATURE_NAMES) lines.push(`    [${JSON.stringify(f)}] = ${w[f]},`);
  lines.push(`  },`, `  bias = ${w.bias},`, `}`);
  writeFileSync(resolve(dataDir, `weights.lua`), lines.join("\n") + "\n");
}

// --- fixtures (emitted as Lua so the tests need no JSON parser) --------------
function luaVal(v: unknown): string {
  if (v === null || v === undefined) return "false";
  if (typeof v === "string") return luaBytes(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "0/0";
  if (Array.isArray(v)) return "{" + v.map(luaVal).join(",") + "}";
  if (typeof v === "object") {
    const parts: string[] = [];
    for (const [k, val] of Object.entries(v as Record<string, unknown>)) parts.push(`[${luaBytes(k)}]=${luaVal(val)}`);
    return "{" + parts.join(",") + "}";
  }
  return "nil";
}
function writeLuaFixture(name: string, value: unknown): void {
  writeFileSync(resolve(fixDir, `${name}.lua`), "-- Auto-generated by tools/gen.ts. Do not edit by hand.\nreturn " + luaVal(value) + "\n");
}
