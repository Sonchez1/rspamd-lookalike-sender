// Feature + score + lookalike fixtures, sourced from the engine benchmark plus hand-picked cases.
interface Case { protected: string[]; name: string; address: string; hosts: string[] }
const cases: Case[] = [];
try {
  const lines = readFileSync(resolve(enginePkg, "../../fixtures/parity.jsonl"), "utf8").trim().split("\n");
  const seen = new Set<string>();
  for (const line of lines) {
    const r = JSON.parse(line) as { protected: string[]; message: { sender_name?: string; sender_address?: string; links?: string[] } };
    const m = r.message;
    const key = `${JSON.stringify(r.protected)}|${m.sender_name}|${m.sender_address}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const hosts = (m.links ?? []).map((l) => normalizeHost(l.replace(/^https?:\/\//, "")));
    cases.push({ protected: r.protected, name: m.sender_name ?? "", address: m.sender_address ?? "", hosts });
    if (cases.length >= 400) break;
  }
} catch (e) { console.error("parity.jsonl not read:", (e as Error).message); }

