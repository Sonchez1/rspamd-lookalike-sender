/** Generates the Lua data tables and the parity fixtures for rspamd-lookalike-sender from the
 *  impersonation-guard engine, so the Lua port is byte-for-byte faithful to it and can be
 *  verified against it. Run via tools/gen.mjs (esbuild bundles this against the engine).
 *
 *  Emitted Lua data (lualib/lua_lookalike/data/):
 *    - cpfold.lua   per-code-point foldSkeleton  (UTS #39 confusable skeleton, case-folded)
 *    - cpcase.lua   per-code-point casefold
 *    - cpnorm.lua   per-code-point casefold(NFKC(c))  (for tokenisation)
 *    - scripts.lua  UTS #39 script ranges
 *    - classes.lua  \p{L}\p{N} and \p{Nd} ranges (word chars / decimal digits)
 *    - weights.lua  the logistic model weights (from scorer_weights.json)
 *
 *  Emitted fixtures (test/fixtures/*.json): expected outputs of the engine for a corpus of
 *  strings, so the Lua unit tests assert equivalence.
 */

